from __future__ import annotations


def module_from_titles(part, rows, L):
    lessons = []
    for order, suffix, module, title, goal, points, terms, code in rows:
        lid = f"{part}-project" if suffix == "project" else f"{part}-{suffix}"
        mid = "project" if suffix == "project" else module
        lessons.append(
            L(
                part,
                lid,
                mid,
                order,
                title,
                goal,
                [("Главное", points[:2]), ("На практике", points[2:] or points[:1])],
                terms,
                code=code,
            )
        )
    return lessons


